// Builds layout/decks-layout.json from the 68 m source layout and layout/hull.json.
// Outlines are the sheet ellipse for the hull's LOA and beam. Each room keeps its size and moves with
// its nearest anchor: stern (x 0), mizzen, main mast and bow. Anchors are the 68 m station positions
// in the source, matched to the hull's stations. So a longer hull adds length between the anchors,
// and rooms near the bow move with the bow.
// Run with: npm run build:hull            (uses layout/hull.json)
//           node scripts/build-layout.mjs <hull.json>   (any hull file)
import {readFileSync, writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {dirname, join} from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const load = (p) => JSON.parse(readFileSync(join(root, p), 'utf8'));
const source = load('layout/source/decks-layout-68m.json');
const hullFile = process.argv[2] ?? 'layout/hull.json';
const hull = load(hullFile);

const SRC_LOA = source.loa; // 68
const SRC_MASTS = {Mizzen: 21.0, Main: 39.9}; // from the 68 m longitudinal section
const loa = hull.loa;
const beam = hull.beam;

// Hull station for each named mast, from its fraction of LOA.
const masts = hull.masts.map((m) => ({...m, x: +(m.x_fraction * loa).toFixed(2)}));
const hullMast = (name) => {
  const m = masts.find((mm) => mm.name === name);
  if (!m) throw new Error(`hull.json has no mast named ${name}`);
  return m.x;
};

// Anchor pairs: source station -> hull station.
const anchors = [
  {src: 0, dst: 0},
  {src: SRC_MASTS.Mizzen, dst: hullMast('Mizzen')},
  {src: SRC_MASTS.Main, dst: hullMast('Main')},
  {src: SRC_LOA, dst: loa},
];
const shiftFor = (cx) => {
  let best = anchors[0];
  for (const a of anchors) if (Math.abs(cx - a.src) < Math.abs(cx - best.src)) best = a;
  return best.dst - best.src;
};

// Sheet ellipse: semi-axes LOA/2 and beam/2, 40 points as in the source outline.
const outline = [];
for (let i = 0; i < 40; i++) {
  const t = (i / 40) * 2 * Math.PI;
  outline.push([+(loa / 2 + (loa / 2) * Math.cos(t)).toFixed(2), +((beam / 2) * Math.sin(t)).toFixed(2)]);
}

const decks = source.decks.map((deck) => ({
  ...deck,
  outline,
  rooms: deck.rooms.map((r) => {
    const [x0, y0, x1, y1] = r.rect;
    const s = shiftFor((x0 + x1) / 2);
    return {...r, rect: [+(x0 + s).toFixed(2), y0, +(x1 + s).toFixed(2), y1]};
  }),
}));

// Program additions authored in hull coordinates (not re-flowed), e.g. A/V and entertainment rooms.
const additions = (hull.additions ?? []).map((a) => ({deck: a.deck, name: a.name, rect: a.rect, kind: a.kind}));
for (const a of additions) {
  const deck = decks.find((dk) => dk.name === a.deck);
  if (!deck) throw new Error(`addition "${a.name}" names a deck that is not in the source: ${a.deck}`);
  deck.rooms.push({name: a.name, rect: a.rect, kind: a.kind});
}

const out = {
  _note: `Generated by scripts/build-layout.mjs from layout/source/decks-layout-68m.json and ${hullFile}. Do not edit by hand. Edit the hull file or the source layout instead.`,
  units: 'm',
  loa,
  beam,
  source: `layout/source/decks-layout-68m.json re-flowed to ${loa} m by ${beam} m (${hullFile})`,
  masts: masts.map(({name, x, foundation_m2, top_m}) => ({name, x, foundation_m2, top_m})),
  decks,
};

writeFileSync(join(root, 'layout/decks-layout.json'), JSON.stringify(out, null, 2) + '\n');
console.log(`decks-layout.json written: ${loa} m by ${beam} m, masts ${masts.map((m) => `${m.name} x ${m.x}`).join(', ')}, ${decks.length} decks`);
